//  クイズの「そっくりさん」の表。
//  そっくりな旗は、わざと同じ問題の選択肢に並べて、見分けるポイントに気づけるようにする。
//  ただし絵文字ではまったく見分けられない組は、同じ問題に並べない（答えようがないため）。
//
//  役割分担:
//    - QuizLookalikes（このファイル）: そっくりな組と、並べてはいけない組の表
//    - EmojiQuizViewModel           : 選択肢を作るときにこの表を使う
//
//  ★ 表の書き方 ★
//    絵文字（JSON の display と同じ文字）で書く。同じカテゴリの中にあるものだけが選択肢に使われる。
//    たとえば「アジアの旗」ではポーランドが出ないので、インドネシアのそっくりさんは「せかい」でだけ並ぶ。

import Foundation

// MARK: - QuizLookalikes

// case のない enum を名前空間として使う理由は ScoreBoard.swift を参照
enum QuizLookalikes {

    /// そっくりなものの組。同じ組の中のものを、優先して選択肢に並べる。← 変更可
    static let groups: [[String]] = [
        ["🇮🇩", "🇲🇨", "🇵🇱"],              // 赤と白（ポーランドは上下が逆）
        ["🇷🇴", "🇹🇩", "🇲🇩", "🇦🇩"],        // 青・黄・赤のたて3色（モルドバとアンドラは紋章つき）
        ["🇳🇱", "🇱🇺"],                    // ルクセンブルクの青は水色
        ["🇸🇳", "🇲🇱", "🇬🇳", "🇨🇲"],        // 緑・黄・赤のたて3色（星があるかどうか、色の順番）
        ["🇮🇪", "🇨🇮", "🇮🇹"],              // 緑・白・オレンジ（赤）の順番
        ["🇳🇴", "🇮🇸"],                    // 赤と青が入れかわっている
        ["🇦🇺", "🇳🇿"],                    // ニュージーランドの星は赤
        ["🇨🇴", "🇪🇨", "🇻🇪"],              // 黄・青・赤（紋章や星があるかどうか）
        ["🇸🇮", "🇸🇰", "🇷🇺", "🇷🇸"],        // 白・青・赤（紋章があるかどうか）
        ["🇭🇹", "🇱🇮"],                    // 青と赤の横2色（紋章がちがう）
        ["🇰🇼", "🇦🇪", "🇯🇴", "🇵🇸", "🇸🇩"],  // 赤・黒・白・緑
        ["🇪🇬", "🇮🇶", "🇸🇾", "🇾🇪"],        // 赤・白・黒の横3色
        ["🇧🇪", "🇩🇪"],                    // 黒・黄・赤（たてか、よこか）
        ["🇲🇾", "🇺🇸", "🇱🇷"],              // 赤と白のしま模様
        ["🇧🇭", "🇶🇦"],                    // ぎざぎざの白（色と、ぎざぎざの数）
        ["🇳🇪", "🇮🇳"],                    // オレンジ・白・緑（まんなかの丸）
        ["🇹🇷", "🇹🇳"],                    // 赤に白の月と星
        ["🇫🇯", "🇹🇻"],                    // 水色にイギリスの旗
        ["🇭🇳", "🇳🇮", "🇸🇻"],              // 青・白・青
        ["🇦🇹", "🇱🇻"],                    // 赤・白・赤（ラトビアは暗い赤）
    ]

    /// 絵文字では見分けられないので、同じ問題に並べない組。← 変更可
    static let neverTogether: [Set<String>] = [
        ["🇮🇩", "🇲🇨"],   // インドネシアとモナコ（本物の旗でも、ちがうのは縦横の比率だけ）
        ["🇷🇴", "🇹🇩"],   // ルーマニアとチャド（ちがうのは青の濃さだけ）
    ]

    /// そっくりさんの一覧（自分は含まない）。
    static func lookalikes(of display: String) -> [String] {
        groups.filter { $0.contains(display) }
            .flatMap { $0 }
            .filter { $0 != display }
    }

    /// 2つを同じ問題に並べてよいか。
    static func canBeTogether(_ a: String, _ b: String) -> Bool {
        !neverTogether.contains([a, b])
    }
}
