    ///   出やすくなってしまわないようにするため（全シール同じ確率の方針を守る）。
    static let all: [String] = {
        var seen = Set<String>()
        var result: [String] = []
        for category in categories {
            for emoji in category.emojis where !seen.contains(emoji) {
                seen.insert(emoji)
                result.append(emoji)
            }
        }
        return result
    }()
