//    ・使える絵文字は Emoji 15.1 まで（対応OS iOS 17.6 で表示できる範囲）。
//      それより新しい絵文字は古い端末で「□」になってしまう。
//    ・子ども向けアプリのため、武器・お酒・たばこ・国旗・宗教に関わる記号・人物
//      （肌の色や性別の違いがあるもの）は入れない。
//    ・🔥（エネルギーの記号）と 🌀（タイトル画面のロゴタイル）は紛らわしいので入れない。
//    ・同じ絵文字を2回書かない。以前は重複で出やすさを変えていたが、
//      いまは「全シールが同じ確率」の方針なので、重複は all で取り除かれる。

